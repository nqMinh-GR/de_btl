"""``synth-generate --kind demo``: deterministic synthetic demo recording (design E §3.4, spec §25.6).

Network from ``cfg.synthetic`` (routes ``R_A..R_E``, service date 2026-10-05, start clock
2026-10-05T12:00:00Z), feeds polled every ``collector.poll_interval_seconds`` with the collector's
stagger (feed index × interval / 3), then the selected scenarios are applied in registry order.
"""

from __future__ import annotations

from collections.abc import Sequence
from datetime import date, datetime, timedelta

from transitpulse.config import ProjectConfig
from transitpulse.contracts.enums import FEED_ORDER
from transitpulse.contracts.envelope import iso_utc, parse_iso_utc
from transitpulse.replay.synthetic.feed_builder import FeedBuilder
from transitpulse.replay.synthetic.gtfs_builder import build_static_model
from transitpulse.replay.synthetic.recording import (
    GENERATOR_VERSION,
    PlannedItem,
    RecordingResult,
    RecordingSpec,
    find_reusable,
    inputs_sha256,
    write_recording,
)
from transitpulse.replay.synthetic.scenarios import SynthPlan, apply_scenarios, normalize_scenarios
from transitpulse.runtime.paths import WorkPaths

DEFAULT_DEMO_DURATION_SECONDS = 600
MAX_DEMO_DURATION_SECONDS = 7200
FIXTURE_KIND_GENERATED = "generated"
SYNTHETIC_SOURCE_URL = "synthetic://transitpulse/{feed}"
PROVENANCE = ("synthetic; generated deterministically by transitpulse.replay.synthetic ({version}, seed {seed}); "
              "NOT MBTA responses and NOT MBTA vehicles/routes")
ATTRIBUTION = "Synthetic test data generated by TransitPulse; schema modelled on MBTA GTFS/GTFS-Realtime JSON. Not MBTA data."


def base_plan(builder: FeedBuilder, start: datetime, duration_seconds: int,
              intervals: dict[str, float]) -> SynthPlan:
    """Captures of the three feeds at the collector's staggered poll instants, in time order."""
    end = start + timedelta(seconds=duration_seconds)
    slots: list[tuple[datetime, int, str]] = []
    for feed in sorted(FEED_ORDER, key=FEED_ORDER.get):
        interval = float(intervals[feed])
        if interval <= 0:
            raise ValueError(f"poll interval of {feed} must be > 0")
        offset = FEED_ORDER[feed] * interval / 3.0
        k = 0
        while True:
            at = start + timedelta(seconds=offset + k * interval)
            if at >= end:
                break
            at = at.replace(microsecond=(at.microsecond // 1000) * 1000)
            slots.append((at, FEED_ORDER[feed], feed))
            k += 1
    slots.sort()
    plan = SynthPlan(builder=builder, start=start, end=end)
    for at, _, feed in slots:
        plan.items.append(PlannedItem(kind="capture", at=at, feed_type=feed, doc=builder.document(feed, at)))
    return plan


def generate_demo(
    cfg: ProjectConfig,
    paths: WorkPaths,
    *,
    seed: int,
    scenarios: Sequence[str] = (),
    duration_seconds: int = DEFAULT_DEMO_DURATION_SECONDS,
) -> RecordingResult:
    if not 60 <= int(duration_seconds) <= MAX_DEMO_DURATION_SECONDS:
        raise ValueError(f"demo duration must be within 60..{MAX_DEMO_DURATION_SECONDS} seconds")
    duration = int(duration_seconds)
    route_ids = tuple(cfg.synthetic.route_ids)
    service_date = date.fromisoformat(cfg.synthetic.service_date)
    start = parse_iso_utc(cfg.synthetic.start_clock)
    scenario_ids = normalize_scenarios(scenarios)
    intervals = {feed: float(cfg.collector.poll_interval_seconds.get(feed, 30.0)) for feed in FEED_ORDER}
    inputs = {
        "kind": "demo",
        "seed": int(seed),
        "scenarios": list(scenario_ids),
        "duration_seconds": duration,
        "route_ids": list(route_ids),
        "service_date": service_date.isoformat(),
        "start_clock": iso_utc(start),
        "poll_interval_seconds": intervals,
        "scope_policy_version": cfg.scope.scope_policy_version,
        "generator_version": GENERATOR_VERSION,
    }
    in_hash = inputs_sha256(inputs)
    recording_id = f"syn-demo-s{int(seed)}-{in_hash[:12]}"
    existing = find_reusable(paths.recordings_root, recording_id, in_hash)
    if existing is not None:
        return existing

    model = build_static_model(route_ids, seed=int(seed), service_date=service_date)
    builder = FeedBuilder(model, seed=int(seed), service_date=service_date)
    plan = base_plan(builder, start, duration, intervals)
    apply_scenarios(plan, scenario_ids, seed=int(seed))
    spec = RecordingSpec(
        recording_id=recording_id,
        fixture_kind=FIXTURE_KIND_GENERATED,
        seed=int(seed),
        scenario_ids=scenario_ids,
        provenance=PROVENANCE.format(version=GENERATOR_VERSION, seed=int(seed)),
        attribution=ATTRIBUTION,
        static_zip=model.zip_bytes(),
        static_feed_version=model.feed_version,
        static_source_url="synthetic://transitpulse/static",
        route_ids=route_ids,
        route_type=cfg.scope.route_type,
        scope_policy_version=cfg.scope.scope_policy_version,
        poll_interval_seconds=intervals["vehicle_positions"],
        feed_source_urls={feed: SYNTHETIC_SOURCE_URL.format(feed=feed) for feed in FEED_ORDER},
        start_clock=start,
        generator={"kind": "demo", "inputs_sha256": in_hash, "inputs": inputs},
        gaps=tuple(plan.gaps),
        extra={"synthetic": {
            "agency_id": "SYN",
            "agency_timezone": model.agency_timezone,
            "service_date": service_date.isoformat(),
            "note": "Synthetic routes are not verified MBTA routes; vehicles are generated.",
        }},
    )
    return write_recording(paths.recordings_root, spec, plan.items)
